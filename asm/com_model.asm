; ================================
; 模板1：标准COM格式程序
; 适用于简单小程序
; ================================
.MODEL TINY          ; COM程序使用TINY模式
.CODE                ; 只有一个段
ORG 100H             ; COM程序从100H开始

START:
    ; 你的代码从这里开始
    
    ; 程序结束，返回DOS
    MOV AH, 4CH      ; DOS功能号：程序终止
    INT 21H          ; 调用DOS中断
    
END START           ; 程序结束点
