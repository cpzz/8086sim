.MODEL SMALL
.STACK 100H

.CODE
START:
    MOV AX, @DATA
    MOV DS, AX

    MOV BL, 80H
    MOV CX, 128

PRINT_LOOP:
    MOV DL, BL
    MOV AH, 02H
    INT 21H

    MOV DL, ' '
    INT 21H

    INC BL

    MOV AL, BL
    AND AL, 0FH
    JNZ NO_NEWLINE
    MOV DL, 0DH
    INT 21H
    MOV DL, 0AH
    INT 21H

NO_NEWLINE:
    LOOP PRINT_LOOP

    MOV AH, 4CH
    INT 21H

END START
